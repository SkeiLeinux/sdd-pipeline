#!/usr/bin/env python3
"""Make an immutable, numbered snapshot of a requirements document.

The pipeline does not care where the requirements come from (wiki export, Word,
Google Docs, a hand-written Markdown file). Convert the document to Markdown with any
tool you like, then run:

    python tools/snapshot.py <input.md> features/<ID>/source [--number] [--force]

What it does:
  * keeps the text as is and only normalizes headings to "## <number> <title>",
    so every requirement can cite a stable section number;
  * numbers headings itself with --number (when the input has no numbering);
  * writes source/source.md (snapshot) and source/index.md (sections and checksums);
  * with --force (new version of the input) compares with the previous snapshot and
    writes source/changes.md: added, removed, changed, renamed and moved sections.

Exit codes: 0 - done, 1 - input problems (nothing written), 2 - usage error.
"""

import argparse
import datetime
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sddlib  # noqa: E402

NUMBERED = re.compile(r"^(\d+(?:\.\d+)*)\.?\s+(.*)$")


def build(lines, number=False, title=None):
    cm = sddlib.code_mask(lines)
    heads = []
    for i, line in enumerate(lines):
        if cm[i]:
            continue
        m = sddlib.ANY_HEADING.match(line)
        if m:
            heads.append([i, len(m.group(1)), m.group(2).strip()])

    errors, warnings = [], []
    doc_title = title
    h1 = [h for h in heads if h[1] == 1]
    if heads and heads[0][1] == 1 and len(h1) == 1 and not NUMBERED.match(heads[0][2]):
        doc_title = doc_title or heads[0][2]
        title_line = heads[0][0]
        heads = heads[1:]
    else:
        title_line = None

    sections = []  # (line, num, title)
    if number:
        base = min((h[1] for h in heads), default=2)
        counters = []
        for ln, lv, text in heads:
            m = NUMBERED.match(text)
            text = m.group(2) if m else text
            depth = max(1, lv - base + 1)
            while len(counters) < depth:
                counters.append(0)
            counters = counters[:depth]
            counters[-1] += 1
            for k in range(depth - 1):
                if counters[k] == 0:
                    counters[k] = 1
            sections.append((ln, ".".join(str(c) for c in counters), text))
    else:
        for ln, lv, text in heads:
            m = NUMBERED.match(text)
            if not m:
                errors.append("line %d: heading '%s' has no number (run with --number to number headings)"
                              % (ln + 1, text))
            else:
                sections.append((ln, m.group(1), m.group(2).strip()))

    seen = {}
    for ln, num, text in sections:
        if num in seen:
            errors.append("line %d: section %s repeats line %d" % (ln + 1, num, seen[num] + 1))
        seen.setdefault(num, ln)
    if errors:
        return None, doc_title, errors, warnings

    first = sections[0][0] if sections else len(lines)
    pre = [l for i, l in enumerate(lines[:first]) if i != title_line]
    body = []
    if any(l.strip() for l in pre):
        warnings.append("text before the first heading is kept as section 0 Preamble")
        body += ["## 0 Preamble", ""] + pre
        if "0" in seen:
            return None, doc_title, ["section 0 already exists, cannot add the preamble"], warnings
    heading_at = {ln: (num, text) for ln, num, text in sections}
    for i in range(first, len(lines)):
        if i in heading_at:
            num, text = heading_at[i]
            depth = num.count(".") + 1
            body.append("#" * min(depth + 1, 6) + " %s %s" % (num, text))
        elif i != title_line:
            body.append(lines[i].rstrip())
    return body, doc_title, errors, warnings


def render(feature, doc_title, origin, body, today):
    head = ["---", "type: source", "feature: %s" % feature, "title: %s" % doc_title,
            "origin: %s" % origin, "snapshot: %s" % today, "---", "",
            "# %s" % doc_title, "",
            "<!-- Snapshot of the input document. Do not edit: a new version of the input is a new "
            "snapshot (tools/snapshot.py --force). -->", ""]
    text = "\n".join(head + body)
    text = re.sub(r"\n{3,}", "\n\n", text).rstrip() + "\n"
    return text


def render_index(feature, secs, today):
    out = ["---", "type: source-index", "feature: %s" % feature, "updated: %s" % today, "---", "",
           "# Source sections", "",
           "<!-- Generated by tools/snapshot.py. Hash - checksum of the section's own text "
           "(without subsections). -->", "",
           "| Section | Title | Lines | Hash |", "|---|---|---|---|"]
    for s in secs:
        out.append("| %s | %s | %d-%d | %s |" % (s["num"], s["title"].replace("|", "\\|"),
                                                 s["start"] + 1, s["end"], s["hash"]))
    return "\n".join(out) + "\n"


def compare(old, new):
    o = {s["num"]: s for s in old}
    n = {s["num"]: s for s in new}
    added, removed, changed, renamed, moved = [], [], [], [], []
    old_by_hash = {}
    for s in old:
        old_by_hash.setdefault(s["hash"], s)
    for s in new:
        if s["num"] not in o:
            prev = old_by_hash.get(s["hash"])
            if prev and prev["num"] not in n:
                moved.append((prev["num"], s["num"], s["title"]))
            else:
                added.append(s)
        else:
            p = o[s["num"]]
            if p["hash"] != s["hash"]:
                changed.append(s)
            if p["title"] != s["title"]:
                renamed.append((s["num"], p["title"], s["title"]))
    moved_from = {m[0] for m in moved}
    for s in old:
        if s["num"] not in n and s["num"] not in moved_from:
            removed.append(s)
    return added, removed, changed, renamed, moved


def render_changes(feature, today, origin, diff):
    added, removed, changed, renamed, moved = diff
    out = ["---", "type: source-changes", "feature: %s" % feature, "updated: %s" % today, "---", "",
           "# Changes in the new source version", "",
           "<!-- Generated by tools/snapshot.py --force. New version: %s. -->" % origin, "",
           "| Change | Section | Title | Note |", "|---|---|---|---|"]
    for s in changed:
        out.append("| changed | %s | %s | text changed |" % (s["num"], s["title"]))
    for s in added:
        out.append("| added | %s | %s | - |" % (s["num"], s["title"]))
    for s in removed:
        out.append("| removed | %s | %s | - |" % (s["num"], s["title"]))
    for num, a, b in renamed:
        out.append("| renamed | %s | %s | was: %s |" % (num, b, a))
    for a, b, t in moved:
        out.append("| moved | %s | %s | was section %s, text unchanged |" % (b, t, a))
    if len(out) == 12:
        out.append("| - | - | - | no changes |")
    return "\n".join(out) + "\n"


def main(argv=None):
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(description="Make a numbered snapshot of a requirements document.")
    ap.add_argument("input", help="Markdown file with the requirements")
    ap.add_argument("out", help="snapshot folder, usually features/<ID>/source")
    ap.add_argument("--feature", help="feature ID (default: name of the folder above OUT)")
    ap.add_argument("--number", action="store_true", help="number headings by their levels")
    ap.add_argument("--force", action="store_true", help="replace an existing snapshot (new input version)")
    ap.add_argument("--title", help="document title (default: the single H1 or the file name)")
    ap.add_argument("--origin", help="where the input came from: URL, file, version (default: file name)")
    args = ap.parse_args(argv)

    if not os.path.isfile(args.input):
        print("error: input file not found: %s" % args.input)
        return 2
    out = os.path.abspath(args.out)
    # Feature folders are "<ID>" or "<ID>-<slug>"; the ID is the first two dash-separated parts.
    feature = args.feature or "-".join(os.path.basename(os.path.dirname(out)).split("-")[:2])
    src_path = os.path.join(out, "source.md")
    if os.path.exists(src_path) and not args.force:
        print("error: %s exists. The snapshot is immutable; for a new input version use --force." % src_path)
        return 2

    lines = sddlib.read_lines(args.input)
    body, doc_title, errors, warnings = build(lines, args.number, args.title)
    if errors:
        for e in errors:
            print("error: " + e)
        print("Nothing written.")
        return 1
    doc_title = doc_title or os.path.splitext(os.path.basename(args.input))[0]
    origin = args.origin or os.path.basename(args.input)
    today = datetime.date.today().isoformat()

    old_secs = None
    if os.path.exists(src_path):
        _, old_secs = sddlib.parse_source(src_path)

    sddlib.write_text(src_path, render(feature, doc_title, origin, body, today))
    _, secs = sddlib.parse_source(src_path)
    sddlib.write_text(os.path.join(out, "index.md"), render_index(feature, secs, today))

    print("Snapshot: %s" % sddlib.rel(src_path, os.getcwd()))
    print("Title: %s. Sections: %d (top level: %d)." % (doc_title, len(secs),
                                                      sum(1 for s in secs if "." not in s["num"])))
    empty = [s["num"] for s in secs if s["end"] - s["start"] <= 1]
    if empty:
        warnings.append("sections without own text: %s" % ", ".join(empty[:15]))
    for w in warnings:
        print("warning: " + w)
    if old_secs is not None:
        diff = compare(old_secs, secs)
        sddlib.write_text(os.path.join(out, "changes.md"), render_changes(feature, today, origin, diff))
        print("Changes vs previous snapshot: changed %d, added %d, removed %d, renamed %d, moved %d "
              "(source/changes.md)." % tuple(len(x) for x in diff))
    print("Check by a human: section numbers match the original, tables and images survived conversion.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
